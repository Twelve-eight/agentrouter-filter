// Run: node tools/gen-filter-core.mjs
import fs from "node:fs";

const SRC = "G:/omp works/.omp/hooks/pre/strip-illegal.ts";
const DST = "G:/omp works/Tools/agentrouter-filter/filter-core.mjs";

const src = fs.readFileSync(SRC, "utf8");
const lines = src.split("\n");

// Locate the pure core by anchors rather than fixed line numbers.
const start = lines.findIndex((l) => l.startsWith("const KEEP = "));
const end = lines.findIndex((l) => l.startsWith("export default function (pi"));
if (start < 0 || end < 0 || end <= start) {
  throw new Error(`anchor not found (start=${start} end=${end})`);
}

let core = lines.slice(start, end).join("\n");

// TypeScript -> JavaScript: drop type annotations only (no logic changes).
core = core
  .replace("const MAP: Record<string, string> = {", "const MAP = {")
  .replace("function fixChar(c: string): string {", "function fixChar(c) {")
  .replace("function sanitize(s: string): string {", "function sanitize(s) {")
  .replace(
    "function deepStrip(value: unknown, changed: { flag: boolean }): unknown {",
    "function deepStrip(value, changed) {",
  )
  .replace("const out: Record<string, unknown> = {};", "const out = {};");

if (/:\s*(string|unknown|Record<|boolean)/.test(core)) {
  const hit = core.split("\n").filter((l) => /:\s*(string|unknown|Record<|boolean)/.test(l));
  throw new Error(`leftover type annotation in generated core:\n${hit.join("\n")}`);
}

const header = `// GENERATED by tools/gen-filter-core.mjs from
// G:/omp works/.omp/hooks/pre/strip-illegal.ts (lines ${start + 1}-${end}).
// Do not edit by hand: edit the hook, then re-run the generator.
// The only transformation applied is removal of TypeScript type annotations.

`;

const footer = `
export { sanitize, deepStrip };
export const CORE_SOURCE = { file: ${JSON.stringify(SRC)}, from: ${start + 1}, to: ${end} };
`;

fs.writeFileSync(DST, header + core + footer);
console.log(`wrote ${DST} (core lines ${start + 1}-${end}, ${core.split("\n").length} lines)`);
