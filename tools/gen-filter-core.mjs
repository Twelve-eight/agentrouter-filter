// Generate filter-core.ts from the omp hook by BYTE-LEVEL COPY.
//
// Node 24 strips TypeScript types natively, and the hook uses only erasable
// syntax (`import type`, `Record<..>`, `: string`, `{ flag: boolean }`), so the
// core can be copied verbatim and imported directly. No regex rewriting of
// annotations happens anywhere -- that approach can silently corrupt a regex
// literal or a string containing ": ".
//
// The only edits are structural:
//   - drop the `import type` line (the hook's type-only import)
//   - drop the `export default function (pi) { .. }` hook wiring
//   - append `export { sanitize, deepStrip };`
//
// Run: node tools/gen-filter-core.mjs
// Verify: node tools/diff-test.mjs  (must print 0 mismatches)
import fs from "node:fs";

const SRC = "G:/omp works/.omp/hooks/pre/strip-illegal.ts";
const DST = "G:/omp works/Tools/agentrouter-filter/filter-core.ts";

const src = fs.readFileSync(SRC, "utf8");
const lines = src.split("\n");

// Anchors, not fixed line numbers: the hook may grow.
const start = lines.findIndex((l) => l.startsWith("const KEEP = "));
const end = lines.findIndex((l) => l.startsWith("export default function (pi"));
if (start < 0 || end < 0 || end <= start) {
  throw new Error(`anchor not found (start=${start} end=${end})`);
}

const core = lines.slice(start, end).join("\n");
if (/^\s*export\s/m.test(core)) {
  throw new Error("core unexpectedly contains an export statement");
}

const header = `// GENERATED by tools/gen-filter-core.mjs -- byte-for-byte copy of
// ${SRC}
// lines ${start + 1}-${end} (the pure core: KEEP/MAP/BOX/SHAPE, fixChar,
// sanitize, deepStrip). Only the \`import type\` line and the
// \`export default function (pi)\` hook wiring are dropped, plus this export.
// Do not edit by hand: edit the hook, then re-run the generator.

`;

fs.writeFileSync(DST, header + core + "\nexport { sanitize, deepStrip };\n");
console.log(`wrote ${DST} (core lines ${start + 1}-${end})`);
